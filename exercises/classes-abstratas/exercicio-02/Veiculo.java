/**
 * Classe Veículo que define os métodos que todos os veículos devem implementar.
 */
public abstract class Veiculo {

    /**
     * Método abstrato para ligar o veículo.
     */
    public abstract void ligar();

    /**
     * Método abstrato para desligar o veículo.
     */
    public abstract void desligar();

    /**
     * Método abstrato para acelerar o veículo.
     */
    public abstract void frente();

    /**
     * Método abstrato para dar ré no veículo.
     */
    public abstract void re();

    /**
     * Método abstrato para parar o veículo.
     */
    public abstract void parar();
    
}
