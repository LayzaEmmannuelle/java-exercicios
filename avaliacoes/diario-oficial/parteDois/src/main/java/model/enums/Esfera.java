package model.enums;

/**
 * Enumeração que representa as diferentes esferas administrativas do governo.
 * 
 * <p>As opções disponíveis são:</p>
 * <ul>
 *   <li>{@link #Estadual} - Representa a esfera estadual.</li>
 *   <li>{@link #Municipal} - Representa a esfera municipal.</li>
 *   <li>{@link #Federal} - Representa a esfera federal.</li>
 * </ul>
 * 
 * <p>Esta enum pode ser utilizada para categorizar entidades ou processos de acordo com sua esfera de atuação.</p>
 * 
 * @author Roma
 */
public enum Esfera {
    /**
     * Esfera estadual.
     */
    Estadual,

    /**
     * Esfera municipal.
     */
    Municipal,

    /**
     * Esfera federal.
     */
    Federal
}