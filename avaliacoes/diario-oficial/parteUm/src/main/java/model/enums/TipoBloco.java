package model.enums;

/**
 * Enumeração que representa os tipos de blocos que podem existir em uma publicação.
 * Pode ser um bloco de texto, imagem ou tabela.
 */
public enum TipoBloco {
    /** Bloco contendo conteúdo textual */
    Texto,

    /** Bloco contendo uma imagem */
    Imagem, 

    /** Bloco contendo uma tabela */
    Tabela 
}
